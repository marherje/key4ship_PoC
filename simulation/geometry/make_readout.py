#!/usr/bin/env python3
"""Generate the SiPadHits readout block for a given number of tiled ASUs.

MultiSegmentation dispatches on the 'wafer' physVolID and needs one entry per
wafer, because every wafer has its own pair of offsets. With 3x3 ASUs that is 36
entries, which is not something to maintain by hand -- hence this script.

The grid inside a wafer is always the plain pixel pitch (SiPad_CellSizeX, the
active pad plus the inter-pad margin); only the offset changes, shifted by a
whole pad array so that the x/y fields come out as the GLOBAL pad indices over
the plane (0..31 for one ASU, 0..63 for 2x2, 0..95 for 3x3). Note the shift is
the pad array SiPad_NPadsPerWaferX*SiPad_CellSizeX, not the physical sensor
size: the segmentation lives in the frame of the sensitive volume, so the
sensor's inactive rim plays no part in it.

Usage:
    python3 make_readout.py [NASUsX] [NASUsY]

Paste the output over the <readout name="SiPadHits"> block of SND_compact.xml,
and set SiPad_NASUsX / SiPad_NASUsY to the same values.
"""
import sys

WAFERS_PER_ASU = 2   # per side, must match SiPad_NWafersX/Y
PADS_PER_WAFER = 16  # per side, must match SiPad_NPadsPerWaferX/Y


def readout(asus_x: int, asus_y: int, indent: str = "    ") -> str:
    cols, rows = asus_x * WAFERS_PER_ASU, asus_y * WAFERS_PER_ASU
    # 'wafer' must hold cols*rows values; keep it last so the bit positions of
    # system/layer/slice/x/y never move.
    bits = max(1, (cols * rows - 1).bit_length())

    segs = []
    for w in range(cols * rows):
        gx, gy = w % cols, w // cols
        # offset = -(pad array - pitch)/2 - gx * (pads per wafer) * pitch
        ox = f"SiPad_SegOffsetX0-{gx}*SiPad_NPadsPerWaferX*SiPad_CellSizeX" if gx else "SiPad_SegOffsetX0"
        oy = f"SiPad_SegOffsetY0-{gy}*SiPad_NPadsPerWaferY*SiPad_CellSizeY" if gy else "SiPad_SegOffsetY0"
        segs.append(
            f'{indent}    <segmentation name="wafer{w}" type="TiledLayerGridXY" key_value="{w}"\n'
            f'{indent}                  grid_size_x="SiPad_CellSizeX" grid_size_y="SiPad_CellSizeY"\n'
            f'{indent}                  offset_x="{ox}"\n'
            f'{indent}                  offset_y="{oy}"\n'
            f'{indent}                  identifier_x="x" identifier_y="y" identifier_layer="layer"/>'
        )

    return (
        f'{indent}<!-- {asus_x}x{asus_y} ASUs = {cols}x{rows} wafers = '
        f'{cols * PADS_PER_WAFER}x{rows * PADS_PER_WAFER} pads. '
        f'Generated by make_readout.py, do not edit by hand. -->\n'
        f'{indent}<readout name="SiPadHits">\n'
        f'{indent}  <segmentation type="MultiSegmentation" key="wafer">\n'
        + "\n".join(segs)
        + f'\n{indent}  </segmentation>\n'
        f'{indent}  <id>system:8,layer:8,slice:4,x:9,y:9,wafer:{bits}</id>\n'
        f'{indent}</readout>'
    )


if __name__ == "__main__":
    nx = int(sys.argv[1]) if len(sys.argv) > 1 else 1
    ny = int(sys.argv[2]) if len(sys.argv) > 2 else nx
    print(readout(nx, ny))
